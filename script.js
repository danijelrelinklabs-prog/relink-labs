function setLanguage(lang) {
  const selectedLanguage = translations[lang] ? lang : "sl";
  const copy = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  localStorage.setItem("relink_lang", selectedLanguage);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = copy[element.dataset.i18nPlaceholder];
    if (value) element.setAttribute("placeholder", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });

  document.title = copy.page_title;
  document
    .getElementById("meta-description")
    ?.setAttribute("content", copy.meta_description);
  document.getElementById("og-title")?.setAttribute("content", copy.page_title);
  document
    .getElementById("og-description")
    ?.setAttribute("content", copy.og_description);

  document
    .getElementById("btn-sl")
    ?.classList.toggle("active", selectedLanguage === "sl");
  document
    .getElementById("btn-en")
    ?.classList.toggle("active", selectedLanguage === "en");
  document
    .getElementById("btn-sl")
    ?.setAttribute("aria-pressed", String(selectedLanguage === "sl"));
  document
    .getElementById("btn-en")
    ?.setAttribute("aria-pressed", String(selectedLanguage === "en"));
}

const savedLanguage = localStorage.getItem("relink_lang") || "sl";
setLanguage(savedLanguage);
